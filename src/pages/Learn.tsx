function LivePanel({ status, concept }: { status: AIStatus | null; concept?: Concept }) {
  const [topic, setTopic] = useState(concept?.title ?? '');
  const [mode, setMode] = useState<ExplainMode>('plain');
  const [question, setQuestion] = useState('');
  const [busy, setBusy] = useState(false);
  const [answer, setAnswer] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);

  if (!status) return null;
  if (!status.available) {
    return (
      <section className="panel quiet" aria-labelledby="h-live">
        <div className="spread"><h2 id="h-live">Explain any topic with live AI</h2><span className="pill planned">Not connected</span></div>
        <p className="small">{status.message} Live explanations for topics outside the sample library need NursePath’s server running with an AI key. The key stays on the server, never in your browser. Everything else in NursePath works without it.</p>
      </section>
    );
  }
  const ask = async () => {
    if (!topic.trim()) return setError('Enter a nursing concept, for example “acid–base balance.”');
    setBusy(true); setError(null); setAnswer(null);
    try { setAnswer(await explainLive(topic.trim(), mode, question.trim())); }
    catch (e) { setError((e as Error).message); }
    finally { setBusy(false); }
  };
  return (
    <section className="panel" aria-labelledby="h-live">
      <div className="spread"><h2 id="h-live">Ask live AI</h2><span className="pill study">Live AI{status.model ? ` · ${status.model}` : ''}</span></div>
      <p className="small muted">Responses are generated on the spot and can be wrong. They do not include references, and they are not reviewed by faculty. No medication dosing. Never include patient information.</p>
      <div className="form-row">
        <div className="field"><label htmlFor="ai-topic">Concept</label><input id="ai-topic" className="input" value={topic} maxLength={120} onChange={(e) => setTopic(e.target.value)} /></div>
        <div className="field"><label htmlFor="ai-mode">Explain it as</label>
          <select id="ai-mode" className="input" value={mode} onChange={(e) => setMode(e.target.value as ExplainMode)}>{EXPLAIN_MODES.map((m) => <option key={m.id} value={m.id}>{m.label}</option>)}</select>
        </div>
      </div>
      <div className="field"><label htmlFor="ai-q">Specific question <span className="optional">optional, up to 300 characters</span></label><input id="ai-q" className="input" value={question} maxLength={300} onChange={(e) => setQuestion(e.target.value)} /></div>
      <div className="row"><button type="button" className="btn primary" onClick={ask} disabled={busy}>{busy ? 'Thinking…' : 'Explain'}</button></div>
      {error && <div className="banner danger" role="alert"><span className="grow">{error}</span></div>}
      {answer && (
        <div className="stack" style={{ gap: 8 }}>
          <span className="source-tag">Live AI response · check with your course materials</span>
          <div className="prose" style={{ whiteSpace: 'pre-wrap' }}>{answer}</div>
        </div>
      )}
    </section>
  );
}

function ConceptView({ concept }: { concept: Concept }) {
  const { ws, update } = useStore();
  const toast = useToast();
  const status = useAIStatus();
  const [mode, setMode] = useState<ExplainMode>('plain');
  const refl = ws.reflections.find((r) => r.topic.toLowerCase() === concept.title.toLowerCase());

  const setReflection = (patch: { confidence?: number; revisit?: boolean }) => {
    update((w) => {
      const existing = w.reflections.find((r) => r.topic.toLowerCase() === concept.title.toLowerCase());
      const now = new Date().toISOString();
      if (existing) return { ...w, reflections: w.reflections.map((r) => (r.id === existing.id ? { ...r, ...patch, updatedAt: now } : r)) };
      return { ...w, reflections: [...w.reflections, { id: uid('ref'), topic: concept.title, confidence: patch.confidence ?? 3, revisit: patch.revisit ?? false, notes: '', updatedAt: now }] };
    });
    toast('Saved to Progress & reflection.');
  };

  return (
    <>
      <a href="#learn" className="small row" style={{ gap: 6 }}><span style={{ width: 16, display: 'inline-flex' }}><Icon name="back" /></span>All concepts</a>
      <header className="page-head">
        <div>
          <p className="eyebrow">{concept.category}</p>
          <h1>{concept.title}</h1>
          <p className="lede">{concept.summary}</p>
        </div>
        <span className="pill sample">Sample library · written in advance</span>
      </header>

      <div className="mode-tabs" role="tablist" aria-label="Explanation style">
        {EXPLAIN_MODES.map((m) => (
          <button key={m.id} id={`tab-${m.id}`} type="button" role="tab" className="mode-tab" aria-selected={mode === m.id} aria-controls="mode-panel" tabIndex={mode === m.id ? 0 : -1}
            onClick={() => setMode(m.id)}
            onKeyDown={(e) => {
              const i = EXPLAIN_MODES.findIndex((x) => x.id === mode);
              if (e.key === 'ArrowRight' || e.key === 'ArrowLeft') {
                e.preventDefault();
                const n = EXPLAIN_MODES[(i + (e.key === 'ArrowRight' ? 1 : EXPLAIN_MODES.length - 1)) % EXPLAIN_MODES.length];
                setMode(n.id);
                document.getElementById(`tab-${n.id}`)?.focus();
              }
            }}>
            <strong>{m.label}</strong><span>{m.hint}</span>
          </button>
        ))}
      </div>

      <section id="mode-panel" role="tabpanel" aria-labelledby={`tab-${mode}`} className="panel" tabIndex={0}>
        <ModeContent concept={concept} mode={mode} />
        <p className="tiny muted" style={{ borderTop: '1px solid var(--line)', paddingTop: 10 }}>Sample content for study support, not clinical guidance. Check with {concept.checkWith}.</p>
      </section>

      <section className="panel" aria-labelledby="h-reflect">
        <h2 id="h-reflect">How confident do you feel?</h2>
        <p className="small muted">This is your own rating, kept separate from quiz scores. It helps the planner suggest review time.</p>
        <div className="chips" role="radiogroup" aria-label="Self-rated confidence">
          {[1, 2, 3, 4, 5].map((n) => (
            <button key={n} type="button" role="radio" aria-checked={refl?.confidence === n} className={`chip${refl?.confidence === n ? ' on' : ''}`} onClick={() => setReflection({ confidence: n })}>
              {n} · {['Not yet', 'Shaky', 'Getting there', 'Fairly sure', 'Confident'][n - 1]}
            </button>
          ))}
        </div>
        <label className="row small"><input type="checkbox" checked={!!refl?.revisit} onChange={(e) => setReflection({ revisit: e.target.checked })} /> Add to my “topics to revisit” list</label>
      </section>

      <LivePanel status={status} concept={concept} />
    </>
  );
}

function ModeContent({ concept, mode }: { concept: Concept; mode: ExplainMode }) {
  switch (mode) {
    case 'plain':
      return <div className="prose">{concept.plain.map((p) => <p key={p}>{p}</p>)}</div>;
    case 'steps':
      return <ol className="steps">{concept.steps.map((s) => <li key={s.title}><div><h3>{s.title}</h3><p className="small" style={{ color: 'var(--ink-2)', marginTop: 2 }}>{s.detail}</p></div></li>)}</ol>;
    case 'analogy':
      return (
        <div className="stack">
          <p className="prose" style={{ fontFamily: 'var(--font-display)', fontSize: '1.2rem' }}>{concept.analogy.intro}</p>
          <div className="table-wrap"><table className="cmp" style={{ minWidth: 0 }}>
            <thead><tr><th scope="col">In nursing</th><th scope="col">In the analogy</th></tr></thead>
            <tbody>{concept.analogy.pairs.map(([a, b]) => <tr key={a}><th scope="row">{a}</th><td>{b}</td></tr>)}</tbody>
          </table></div>
          <p className="small muted"><strong>Where the analogy breaks down:</strong> {concept.analogy.limits}</p>
        </div>
      );
    case 'compare':
      return (
        <div className="table-wrap"><table className="cmp">
          <caption>{concept.compare.caption}</caption>
          <thead><tr>{concept.compare.columns.map((c, i) => <th key={i} scope="col">{c || <span className="sr-only">Feature</span>}</th>)}</tr></thead>
          <tbody>{concept.compare.rows.map((r) => <tr key={r[0]}>{r.map((cell, i) => (i === 0 ? <th key={i} scope="row">{cell}</th> : <td key={i}>{cell}</td>))}</tr>)}</tbody>
        </table></div>
      );
    case 'scenario':
      return (
        <div className="stack">
          <span className="source-tag" style={{ alignSelf: 'flex-start' }}>Fictional scenario · not a real patient</span>
          <p className="prose">{concept.scenario.setup}</p>
          <p className="small muted">Think through each question before opening the discussion.</p>
          {concept.scenario.prompts.map((p, i) => (
            <details key={i} className="discuss"><summary>{i + 1}. {p.question}</summary><p>{p.discussion}</p></details>
          ))}
        </div>
      );
    case 'quiz':
      return <Quiz concept={concept} />;
  }
}

function Quiz({ concept }: { concept: Concept }) {
  const { update } = useStore();
  const toast = useToast();
  const [answers, setAnswers] = useState<(number | null)[]>(() => concept.quiz.map(() => null));
  const [submitted, setSubmitted] = useState(false);
  const correct = answers.filter((a, i) => a === concept.quiz[i].answer).length;
  const submit = () => {
    setSubmitted(true);
    update((w) => ({ ...w, quizAttempts: [...w.quizAttempts, { id: uid('qz'), conceptId: concept.id, conceptTitle: concept.title, correct, total: concept.quiz.length, takenAt: new Date().toISOString() }] }));
    toast(`Quiz saved: ${correct} of ${concept.quiz.length}.`);
  };
  return (
    <div className="stack">
      <p className="small muted">Practice questions to check your understanding. Your score is saved under Progress. It is a study aid, not a measure of clinical readiness.</p>
      {concept.quiz.map((q, qi) => (
        <fieldset key={qi} className="quiz-q">
          <legend style={{ fontWeight: 650 }}>{qi + 1}. {q.prompt}</legend>
          {q.options.map((o, oi) => {
            const chosen = answers[qi] === oi;
            const cls = submitted ? (oi === q.answer ? ' correct' : chosen ? ' wrong' : '') : '';
            return (
              <label key={oi} className={`quiz-opt${cls}`}>
                <input type="radio" name={`q-${concept.id}-${qi}`} checked={chosen} disabled={submitted} onChange={() => setAnswers(answers.map((a, i) => (i === qi ? oi : a)))} />
                <span>{o}{submitted && oi === q.answer && <strong> — correct answer</strong>}{submitted && chosen && oi !== q.answer && <strong> — your answer</strong>}</span>
              </label>
            );
          })}
          {submitted && <p className="rationale"><strong>Rationale:</strong> {q.rationale}</p>}
        </fieldset>
      ))}
      {!submitted ? (
        <button type="button" className="btn primary" style={{ alignSelf: 'flex-start' }} disabled={answers.some((a) => a === null)} onClick={submit}>Check my answers</button>
      ) : (
        <div className="spread">
          <strong>{correct} of {concept.quiz.length} correct</strong>
          <button type="button" className="btn" onClick={() => { setAnswers(concept.quiz.map(() => null)); setSubmitted(false); }}>Try again</button>
        </div>
      )}
      {!submitted && answers.some((a) => a === null) && <p className="tiny muted">Answer every question to check your answers.</p>}
    </div>
  );
}
